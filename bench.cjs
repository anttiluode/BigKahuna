// Protocol fixed in docs/protocol.md before first run. No parameter tuning.
const fs=require('node:fs');
const K=require('./core.js');
const mean=a=>a.reduce((s,v)=>s+v,0)/a.length;
const sd=a=>Math.sqrt(a.reduce((s,v)=>s+(v-mean(a))**2,0)/(a.length-1));
const seeds=Array.from({length:20},(_,i)=>101+i),worlds={};
for(const preset of Object.keys(K.PRESETS)){
  const runs=seeds.map(seed=>{const r=K.run({preset,seed,rounds:1200});delete r.history;return r;});
  const summary=Object.fromEntries(K.NAMES.map(n=>[n,{
    loss:mean(runs.map(r=>r.metrics[n].loss)),sd:sd(runs.map(r=>r.metrics[n].loss)),
    mse:mean(runs.map(r=>r.metrics[n].mse)),queries:mean(runs.map(r=>r.metrics[n].queries))
  }]));
  const comparisons=Object.fromEntries(['passive','fixed','random'].map(n=>{
    const differences=runs.map(r=>r.metrics.active.loss-r.metrics[n].loss);
    return[n,{meanDifference:mean(differences),sdDifference:sd(differences),wins:differences.filter(x=>x<0).length,
      improvement:1-summary.active.loss/summary[n].loss}];
  }));
  worlds[preset]={summary,comparisons,runs};
  console.log(preset,JSON.stringify(summary));
}
const gate=Object.values(worlds.directional.comparisons).every(c=>c.improvement>=.05&&c.wins>=15);
const receipt={version:K.VERSION,protocol:'docs/protocol.md',seeds,rounds:1200,directionalGate:gate?'PASS':'FAIL',worlds};
fs.mkdirSync('results',{recursive:true});fs.writeFileSync('results/benchmark.json',JSON.stringify(receipt,null,2)+'\n');
const browser={version:receipt.version,seeds:seeds.length,rounds:1200,directionalGate:receipt.directionalGate,
  worlds:Object.fromEntries(Object.entries(worlds).map(([k,v])=>[k,{summary:v.summary,comparisons:v.comparisons}]))};
fs.writeFileSync('results/summary.js','/* Generated by node bench.cjs. */\nwindow.BIGKAHUNA_BENCHMARK = '+JSON.stringify(browser,null,2)+';\n');
console.log('Directional gate:',receipt.directionalGate);
